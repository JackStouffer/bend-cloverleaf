// Regenerates the API spec and the typed client from the Bend route table.
//
//   node scripts/gen-api.mjs          write backend/openapi.json and src/api/schema.ts
//   node scripts/gen-api.mjs --check  fail if either differs from what the table gives
//
// The spec comes from `bend web/spec.bend`, so bend has to be on PATH. Both
// files are committed, so an API change always shows up in review, and the
// nginx image builds the frontend without bend.
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const frontend = join(dirname(fileURLToPath(import.meta.url)), "..");
const backend = join(frontend, "..", "backend");
const specPath = join(backend, "openapi.json");
const typesPath = join(frontend, "src", "api", "schema.ts");
const check = process.argv.includes("--check");

const run = spawnSync("bend", ["web/spec.bend"], {
  cwd: backend,
  encoding: "utf8",
  env: { ...process.env, BEND_NO_TELEMETRY: "1" },
  maxBuffer: 64 * 1024 * 1024,
});
if (run.error !== undefined) {
  console.error(`gen-api: could not run bend: ${run.error.message}`);
  process.exit(1);
}
if (run.status !== 0) {
  console.error(run.stdout, run.stderr);
  console.error(
    `gen-api: bend web/spec.bend exited with ${String(run.status)}`,
  );
  process.exit(1);
}
const spec = run.stdout;
JSON.parse(spec);

const header =
  "// Generated by `npm run gen:api` from backend/openapi.json. Don't edit.\n\n";
const types = header + astToString(await openapiTS(spec));

function read(path) {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return null;
  }
}

const outputs = [
  [specPath, spec],
  [typesPath, types],
];
if (check) {
  const stale = outputs
    .filter(([path, text]) => read(path) !== text)
    .map(([path]) => path);
  if (stale.length > 0) {
    console.error(
      `gen-api: out of date, run npm run gen:api:\n  ${stale.join("\n  ")}`,
    );
    process.exit(1);
  }
  console.log("gen-api: spec and client match the route table");
} else {
  for (const [path, text] of outputs) writeFileSync(path, text);
  console.log("gen-api: wrote backend/openapi.json and src/api/schema.ts");
}
